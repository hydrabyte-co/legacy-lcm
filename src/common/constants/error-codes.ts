/**
 * Get error severity for a given error code
 */
export function getErrorSeverity(errorCode: string): string {
  return ERROR_SEVERITY_MAPPING[errorCode] || ERROR_SEVERITY.MEDIUM;
}

/**
 * Get business domain for a given error code
 */
export function getErrorDomain(errorCode: string): string {
  return ERROR_DOMAIN_MAPPING[errorCode] || 'GENERAL';
}

/**
 * Check if error code is critical
 */
export function isCriticalError(errorCode: string): boolean {
  return getErrorSeverity(errorCode) === ERROR_SEVERITY.CRITICAL;
}

